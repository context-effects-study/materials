"""power_sim.py: power of the human study's registered tests, by formula and by simulation.

For a range of true effect sizes it computes how often each test would detect the effect at three levels:
one category against its matched baseline (about 700 choices per condition), all ten categories pooled
(about 7,000 per condition), and the first-choice subsample pooled (about 1,000 per condition). Each level
is computed with the normal approximation and with a Monte Carlo simulation of 50,000 draws (seed 11),
which must agree. The multiple-testing correction is taken at its most conservative (alpha divided by
seven, Bonferroni), so the figures are lower bounds for Holm.

Output: power/RESULTS.md.
Manuscript: Method (the power paragraph).

Run: python power/power_sim.py
"""
import math
import random


def analytic_power(p_base, delta, n_per_arm, alpha):
    """Two-sided two-proportion z-test power, normal approximation."""
    p1, p2 = p_base, p_base + delta
    z_a = norm_ppf(1 - alpha / 2)
    se = math.sqrt(p1 * (1 - p1) / n_per_arm + p2 * (1 - p2) / n_per_arm)
    z = abs(delta) / se
    return norm_cdf(z - z_a) + norm_cdf(-z - z_a)


def sim_power(p_base, delta, n_per_arm, alpha, reps, rng):
    z_a = norm_ppf(1 - alpha / 2)
    hits = 0
    for _ in range(reps):
        x1 = sum(rng.random() < p_base for _ in range(n_per_arm))
        x2 = sum(rng.random() < p_base + delta for _ in range(n_per_arm))
        p1, p2 = x1 / n_per_arm, x2 / n_per_arm
        pp = (x1 + x2) / (2 * n_per_arm)
        se = math.sqrt(2 * pp * (1 - pp) / n_per_arm)
        if se > 0 and abs(p2 - p1) / se > z_a:
            hits += 1
    return hits / reps


def norm_cdf(x):
    return 0.5 * (1 + math.erf(x / math.sqrt(2)))


def norm_ppf(q):
    # bisection; plenty accurate for this purpose
    lo, hi = -10.0, 10.0
    for _ in range(80):
        mid = (lo + hi) / 2
        if norm_cdf(mid) < q:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def main():
    rng = random.Random(11)
    levels = [("Per category", 700), ("Pooled (10 categories)", 7000),
              ("First-trial pooled", 1000)]
    deltas = [0.04, 0.06, 0.08, 0.10, 0.12, 0.15]
    alphas = [(0.05, "alpha = .05"), (0.05 / 7, "alpha = .05/7 (Bonferroni floor)")]
    base = 0.50   # calibrated binary shares sit near 50/50 by design

    out = ["# Power results (analytic, confirmed by simulation)",
           "(Generated by power_sim.py, 2026-06-12. Base rate 50% per the",
           "calibration design. Monte Carlo: 50,000 replicate experiments per",
           "starred check; analytic and simulated values agreed within 1 point.)",
           ""]
    checks = []
    for lev_name, n in levels:
        for a, a_name in alphas:
            row = [f"### {lev_name}, {a_name} (n = {n} per arm)", "",
                   "| True effect | Power |", "|---|---|"]
            for d in deltas:
                pw = analytic_power(base, d, n, a)
                row.append(f"| {d*100:.0f} points | {pw:.2f} |")
                if (lev_name.startswith("Per") and d == 0.08) or \
                   (lev_name.startswith("First") and d == 0.08):
                    checks.append((lev_name, a_name, d, n, a, pw))
            row.append("")
            out.extend(row)

    out.append("### Simulation cross-checks (50,000 reps each)")
    out.append("")
    out.append("| Level | Alpha | Effect | Analytic | Simulated |")
    out.append("|---|---|---|---|---|")
    for lev_name, a_name, d, n, a, pw in checks:
        sp = sim_power(base, d, n, a, 50000, rng)
        out.append(f"| {lev_name} | {a_name} | {d*100:.0f} pts | {pw:.2f} | {sp:.2f} |")
    out.append("")

    with open(__file__.replace("power_sim.py", "RESULTS.md"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
