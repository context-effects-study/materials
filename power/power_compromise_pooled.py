"""power_compromise_pooled.py: power of the pooled human compromise test after the descriptive compromise cells
leave it, and of the other five non-similarity effects, at the registered Holm family of six.

The compromise cells whose target starts at or above 50 percent are reported descriptively and leave the
confirmatory test; the cells left are read from stimuli.json through the same design index the analysis
uses. The relative share also drops the participants who choose the new extreme. Analytic power and a
simulation that applies the full registered criterion (Holm, direction and Bayes factor; 20,000 runs, seed
20260929).

Output: power/POWER_COMPROMISE_POOLED.md.
Manuscript: Method (the power paragraph) and Web Appendix E.

Run: python power/power_compromise_pooled.py
"""
import argparse, math, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
_ANALYSIS = os.path.abspath(os.path.join(HERE, "..", "analysis"))
if _ANALYSIS not in sys.path:
    sys.path.append(_ANALYSIS)   # appended so a caller's own copy of the analysis code keeps precedence
import analyze   # noqa: E402  (the Design index: which compromise cells are descriptive)
import statlib   # noqa: E402
from registered_constants import C as RC  # noqa: E402

BASE = 0.425                   # calibrated binary share (band midpoint), used by the simulation
FAMILY = 6                     # the registered Holm family of the six non-similarity effects
POOLED_OTHER_N = 7000          # the other five effects: about 7,000 choices per arm pooled
EXTREME_SHARES = (0.15, 0.20, 0.30)
EFFECTS_PP = (4, 5)


def norm_cdf(x):
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def z_two_sided(alpha):
    return statlib.norm_ppf(1.0 - alpha / 2.0)


def power_directional(delta, se, alpha):
    """P(significant at two-sided alpha AND in the predicted direction)."""
    return norm_cdf(delta / se - z_two_sided(alpha))


def mde(se, alpha, power=0.80):
    return (z_two_sided(alpha) + statlib.norm_ppf(power)) * se


def compromise_slices():
    """(category, tier, size) of the backbone numbers compromise slices that stay confirmatory."""
    d = analyze.Design.from_stimuli()
    import json
    S = json.load(open(analyze.STIMULI_PATH, encoding="utf-8"))
    out = []
    for r in S["stimuli"]:
        if r["structure"] != "SOT":
            continue
        cat, tier = r["category"], int(r["memorization_tier"])
        if cat in d.price_free:
            continue
        if (cat, tier, "numbers") in d.compromise_descriptive:
            continue
        out.append((cat, tier, 700 if tier == 3 else 350))
    all_n = sum(1 for r in S["stimuli"] if r["structure"] == "SOT" and r["category"] not in d.price_free)
    return sorted(out), d, all_n


def se_pooled(n_t, n_c, var=0.25):
    return math.sqrt(var / n_t + var / n_c)


def simulate(slices, e, delta, reps, seed, alphas):
    """The registered stratified estimator on simulated slices: each slice's compromise cell loses a
    Binomial(n, e) number of new-extreme choosers, the rest choose the target at BASE + delta; the
    binary control at BASE; one choice per participant (the backbone's no-repeat design)."""
    rng = random.Random(seed)
    hits = {a: 0 for a in alphas}
    hits_bf = {a: 0 for a in alphas}
    for _ in range(reps):
        parts = []
        for _cat, _tier, n in slices:
            n_ext = rng.binomialvariate(n, e)
            nt = n - n_ext
            kt = rng.binomialvariate(nt, BASE + delta)
            kc = rng.binomialvariate(n, BASE)
            parts.append((kt, nt, kc, n))
        W = sum(nt for _, nt, _, _ in parts)
        d = sum(nt / W * (kt / nt - kc / nc) for kt, nt, kc, nc in parts)
        var = sum((nt / W) ** 2 * (kt / nt) * (1 - kt / nt) / nt + (nt / W) ** 2 * (kc / nc) * (1 - kc / nc) / nc
                  for kt, nt, kc, nc in parts)
        se = math.sqrt(var)
        z = d / se
        bf = statlib.bf10_halfnormal(d, se, RC.BF_PRIOR_SCALE_PP / 100.0)
        for a in alphas:
            sig = (2 * (1 - norm_cdf(abs(z))) < a) and d > 0
            hits[a] += sig
            hits_bf[a] += sig and bf > RC.BF_GATE
    return {a: hits[a] / reps for a in alphas}, {a: hits_bf[a] / reps for a in alphas}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=20000)
    ap.add_argument("--out", default=os.path.join(HERE, "POWER_COMPROMISE_POOLED.md"))
    args = ap.parse_args()
    slices, design, n_all = compromise_slices()
    n_c = sum(n for _, _, n in slices)
    a6, a1 = RC.HOLM_ALPHA / FAMILY, RC.HOLM_ALPHA
    desc_numbers = sorted(s for s in design.compromise_descriptive if s[2] == "numbers")
    L = ["# Power of the pooled compromise test after the descriptive cells leave it", "",
         f"(Generated by power_compromise_pooled.py, 2026-09-29. Analytic values use the conservative variance "
         f"p(1 - p) = 0.25; the simulation uses the calibrated 42.5 percent baseline, {args.reps:,} runs per row, "
         "seed 20260929, and applies the full registered criterion. Standard library only.)", "",
         "## The cells the test runs on", "",
         f"Of the {n_all} backbone compromise cells, {len(desc_numbers)} numbers cells are descriptive "
         "(target starts at or above 50 percent): " + ", ".join(f"{c} tier {t}" for c, t, _ in desc_numbers) +
         ". The eighth descriptive cell, the pictures water-bottles pair, is in the format module, not the "
         "backbone.", "",
         "| category | tier | compromise choices |", "|---|---|---|"]
    for c, t, n in slices:
        L.append(f"| {c} | {t} | {n:,} |")
    L += [f"| **total** | | **{n_c:,}** |", "",
          f"Before the new-extreme choosers leave, the compromise cell holds {n_c:,} choices against {n_c:,} "
          "binary choices on the same slices (the full backbone would give 7,000 against 7,000).", "",
          "## Power of the pooled compromise test", "",
          "| share choosing the new extreme | choices left in the relative share | SE (points) | effect | "
          "power at .05/6 (first Holm step) | power at .05 | simulated, full criterion, .05/6 | "
          "simulated, full criterion, .05 |",
          "|---|---|---|---|---|---|---|---|"]
    mde_rows = []
    for e in EXTREME_SHARES:
        n_t = n_c * (1 - e)
        se = se_pooled(n_t, n_c)
        for dpp in EFFECTS_PP:
            sim, sim_bf = simulate(slices, e, dpp / 100.0, args.reps, 20260929 + int(e * 100) + dpp, (a6, a1))
            L.append(f"| {int(e * 100)} percent | {n_t:,.0f} | {se * 100:.2f} | {dpp} points | "
                     f"{power_directional(dpp / 100, se, a6):.2f} | {power_directional(dpp / 100, se, a1):.2f} | "
                     f"{sim_bf[a6]:.2f} | {sim_bf[a1]:.2f} |")
        mde_rows.append((e, n_t, se))
    L += ["", "## Smallest compromise effect detected with 0.80 power", "",
          "| share choosing the new extreme | at .05/6 (first Holm step) | at .05 |", "|---|---|---|"]
    for e, n_t, se in mde_rows:
        L.append(f"| {int(e * 100)} percent | {mde(se, a6) * 100:.1f} points | {mde(se, a1) * 100:.1f} points |")
    se5 = se_pooled(POOLED_OTHER_N, POOLED_OTHER_N)
    a7 = RC.HOLM_ALPHA / 7
    L += ["", "## The other five non-similarity effects (frequency, range, phantom, upscaling, extremity)", "",
          "Each pooled test compares about 7,000 treatment choices with about 7,000 control choices.", "",
          "| effect | power at .05/6 (the registered family of six) | power at .05/7 (the figure the manuscript "
          "printed) | power at .05 | smallest effect at 0.80 power, .05/6 |", "|---|---|---|---|---|"]
    for dpp in (4, 5, 6):
        L.append(f"| {dpp} points | {power_directional(dpp / 100, se5, a6):.2f} | "
                 f"{power_directional(dpp / 100, se5, a7):.2f} | {power_directional(dpp / 100, se5, a1):.2f} | "
                 f"{mde(se5, a6) * 100:.1f} points |")
    # tier-level compromise, descriptive by protocol (the manuscript's tier-level power claim)
    by_tier = {}
    for c, t, n in slices:
        by_tier[t] = by_tier.get(t, 0) + n
    L += ["", "## Tier-level compromise (descriptive by protocol; for the manuscript's tier-level sentence)", "",
          "| tier | compromise choices | power at 6 points, .05/6, 20 percent extreme choosers |", "|---|---|---|"]
    for t in sorted(by_tier):
        se_t = se_pooled(by_tier[t] * 0.8, by_tier[t])
        L.append(f"| {t} | {by_tier[t]:,} | {power_directional(0.06, se_t, a6):.2f} |")
    s15 = se_pooled(n_c * 0.85, n_c)
    s30 = se_pooled(n_c * 0.70, n_c)
    L += ["", "## Reading", "",
          f"After the descriptive cells leave, the pooled compromise test runs on {n_c:,} compromise choices "
          f"against {n_c:,} binary choices, and the relative share then drops the new-extreme choosers. At the "
          f"first Holm step of the six-effect family its power at a 4-point effect is "
          f"{power_directional(0.04, s30, a6):.2f} to {power_directional(0.04, s15, a6):.2f} "
          "(30 to 15 percent extreme choosers) and at a 5-point effect "
          f"{power_directional(0.05, s30, a6):.2f} to {power_directional(0.05, s15, a6):.2f}. The smallest "
          f"compromise effect it detects with 0.80 power is {mde(s15, a6) * 100:.1f} to {mde(s30, a6) * 100:.1f} "
          "points at .05/6. The other five non-similarity effects keep power of "
          f"{power_directional(0.04, se5, a6):.2f} at a 4-point effect at .05/6 (the manuscript's .05/7 gives "
          f"{power_directional(0.04, se5, a7):.2f}).", ""]
    text = "\n".join(L)
    open(args.out, "w", encoding="utf-8", newline="\n").write(text)
    print(text)


if __name__ == "__main__":
    main()
