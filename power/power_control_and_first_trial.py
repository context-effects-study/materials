"""power_control_and_first_trial.py: the power of the frequency-decoy positive control and of the pooled test of
first choices.

The positive control is judged on the premium-target cells of the stimulus sets that we built whose two-option
pair met the calibration rule: the external hard drives and the televisions at the new values (350 treatment and
350 control choices each) and the robot vacuums (700 and 700). The test of first choices pools 14 cells of 50
first choices and 3 cells of 100. Each run draws every choice at a control share of 0.425 and applies the
registered criterion: the predicted direction, significance (.05 for the control, .05 divided by six for the test
of first choices) and a half-normal Bayes factor above 3. 4,000 runs per row; standard library only.

Output: power/POWER_CONTROL_AND_FIRST_TRIAL.md.
Manuscript: Analysis Plan (Validity Criteria, Human Benchmarks) and Web Appendix E.

Run: python power/power_control_and_first_trial.py      (about 5 minutes)
"""
import argparse, math, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "analysis")))
import statlib  # noqa: E402

BASE = 0.425
CONTROL_CELLS = [(350, 350), (350, 350), (700, 700)]
FIRST_TRIAL_CELLS = [(50, 50)] * 14 + [(100, 100)] * 3


def power(effect, cells, alpha, reps, seed):
    rng = random.Random(seed)
    hit = 0
    nt_tot = sum(nt for nt, _ in cells)
    for _ in range(reps):
        d = v = 0.0
        for nt, nc in cells:
            kt = sum(1 for _ in range(nt) if rng.random() < BASE + effect)
            kc = sum(1 for _ in range(nc) if rng.random() < BASE)
            mt, mc = kt / nt, kc / nc
            w = nt / nt_tot
            d += w * (mt - mc)
            v += w * w * (mt * (1 - mt) / nt + mc * (1 - mc) / nc)
        se = math.sqrt(v)
        if (statlib.two_sided_p_from_z(d / se) < alpha and d > 0
                and statlib.bf10_halfnormal(d, se, 0.10) > 3):
            hit += 1
    return hit / reps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=4000)
    args = ap.parse_args()
    lines = ["# Power of the frequency-decoy control and of the pooled first-trial test (2026-11-25)", "",
             f"(Generated by power_control_and_first_trial.py, {args.reps} simulated runs per row; a share near 0.5 "
             f"has a Monte Carlo standard error of about {math.sqrt(0.25 / args.reps):.3f}.)", "",
             "| Test | Cells | Level | True effect | Share of runs that pass the criterion |", "|---|---|---|---|---|"]
    for i, e in enumerate((0.04, 0.06, 0.08)):
        lines.append(f"| Frequency-decoy positive control | hard drives and televisions at the new values, robot "
                     f"vacuums (1,400 treatment choices) | .05 | {e * 100:.0f} points | "
                     f"{power(e, CONTROL_CELLS, 0.05, args.reps, 10 + i):.2f} |")
    for i, e in enumerate((0.04, 0.06, 0.08)):
        lines.append(f"| Pooled first-trial test | 17 cells of first choices (1,000 treatment choices) | .05/6 | "
                     f"{e * 100:.0f} points | {power(e, FIRST_TRIAL_CELLS, 0.05 / 6, args.reps, 20 + i):.2f} |")
    text = "\n".join(lines) + "\n"
    open(os.path.join(HERE, "POWER_CONTROL_AND_FIRST_TRIAL.md"), "w", encoding="utf-8", newline="\n").write(text)
    print(text)


if __name__ == "__main__":
    main()
