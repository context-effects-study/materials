#!/usr/bin/env python3
"""build_worker_data.py: build the script tables the assignment service hands out.

The words, pictures and price-free surveys each deal 2,100 to 2,800 pre-built scripts, more than a
Qualtrics randomizer can hold. This script takes the same balanced deals (surveys/deal.py) and the same
option rendering (surveys/generate_survey.py) and writes them into the service's data bundle, compressed.
The service assigns the least-used script of the requested survey, so presentations stay even; it assigns
scripts only and never receives responses.

Output: surveys/assign_worker/src/scripts_data.js (the bundle) and src/manifest.json (per-survey script
counts, sizes and deal hashes; the deal hashes must match the ones recorded in surveys/out/*_MAPPING.json).

Run: python surveys/assign_worker/build_worker_data.py [--image-host <URL of the pictures host>]
"""
from __future__ import annotations
import argparse, base64, gzip, hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Layout: the survey engine is the sibling
# human_qualtrics/ in the working repository (this worker lives at surveys/assign_worker/) and the
# parent directory in the public deposit (surveys/assign_worker/). Take the first that exists.
HUMAN = next((p for p in (os.path.abspath(os.path.join(HERE, "..", "human_qualtrics")),
                          os.path.abspath(os.path.join(HERE, "..")))
              if os.path.exists(os.path.join(p, "generate_survey.py"))),
             os.path.abspath(os.path.join(HERE, "..", "human_qualtrics")))
sys.path.insert(0, HUMAN)
import deal                       # the fixed balanced deals (Surveys 3 & 4)
import generate_survey as GS      # cells_to_pairs: the SAME setter payload the in-Qualtrics randomizer used

# The three arms that exceeded the importer cap. Each entry: (deal function call, trial count k, image arm?).
# k and the deal seeds match generate_survey.main() exactly, so the Worker serves the identical scripts.

def build_arm(arm, scripts, k, image_host=None):
    cats, by_cell, pub, inv, pf = deal.load()
    # Optionally re-point the picture image host (default keeps generate_survey's placeholder so the
    # launch guard stays honest). cells_to_pairs reads GS.HOSTBASE for picture URLs.
    if image_host is not None:
        GS.HOSTBASE = image_host.rstrip("/")
    payloads = [dict(GS.cells_to_pairs(i + 1, sc, by_cell, cats, arm)) for i, sc in enumerate(scripts)]
    # the deal hash that generate_survey stamps into assignment_version (same input -> same value)
    deal_sha = hashlib.sha256(json.dumps(scripts, sort_keys=True).encode()).hexdigest()[:12]
    return payloads, deal_sha


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--image-host", default=None,
                    help="picture-arm image host base (default: keep generate_survey placeholder).")
    ap.add_argument("--out", default=os.path.join(HERE, "src", "scripts_data.js"))
    args = ap.parse_args()

    cats, by_cell, pub, inv, pf = deal.load()
    s4, _ = deal.deal_pricefree(pf)
    sw, _, _ = deal.deal_format("words")
    sp, _, _ = deal.deal_format("pictures")
    arms_src = {
        # arm key -> (scripts, k trials, picture?)
        "price-free": (s4, 3, False),
        "words": (sw, 3, False),
        "pictures": (sp, 3, True),
    }

    manifest = {}
    data = {}
    for arm, (scripts, k, is_pic) in arms_src.items():
        payloads, deal_sha = build_arm(arm, scripts, k, args.image_host if is_pic else None)
        blob = json.dumps(payloads, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        gz = gzip.compress(blob, 9)
        b64 = base64.b64encode(gz).decode("ascii")
        data[arm] = b64
        manifest[arm] = {"n_scripts": len(payloads), "k_trials": k, "deal_sha256_12": deal_sha,
                         "picture_arm": is_pic, "raw_bytes": len(blob), "gz_b64_bytes": len(b64)}
        print(f"[build_worker_data] {arm}: {len(payloads)} scripts, k={k}, "
              f"deal_sha={deal_sha}, raw {len(blob)//1024}KB -> gz_b64 {len(b64)//1024}KB")

    # Emit an ES module the Worker imports. The big arrays live as gzip+base64 strings (decompressed once
    # at Worker startup), keeping the deployed bundle ~0.4 MB total despite ~21 MB of raw script JSON.
    lines = [
        "// scripts_data.js - GENERATED by build_worker_data.py. DO NOT EDIT BY HAND.",
        "// Per-arm balanced script tables (gzip+base64). Decompressed once in the Worker.",
        "// Built with deal.py + generate_survey.cells_to_pairs so the embedded-data payload",
        "// is byte-identical to the in-Qualtrics randomizer the design used before the importer cap.",
        f"export const MANIFEST = {json.dumps(manifest, indent=2)};",
        "export const ARMS_GZ_B64 = {",
    ]
    for arm, b64 in data.items():
        lines.append(f"  {json.dumps(arm)}: {json.dumps(b64)},")
    lines.append("};")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    # also write a plain manifest for humans / the regen script
    with open(os.path.join(HERE, "src", "manifest.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=2)
    print(f"[build_worker_data] wrote {args.out} ({os.path.getsize(args.out)//1024}KB)")


if __name__ == "__main__":
    main()
